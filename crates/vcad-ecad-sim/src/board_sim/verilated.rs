//! Verilator-backed [`ChipBackend`]: the artifact's Verilog, built at run time into
//! a shared library and driven over a thin C ABI.
//!
//! Neither cargo nor CI needs Verilator: the model is built the first time an
//! artifact is simulated, then cached next to the extracted artifact
//! (`<store>/<sha>/model-<key>/libvcad_hdl.so`, keyed by the shim source,
//! the Verilator version and the build flags). Needs `verilator` (or
//! `$VERILATOR`) and a C++ compiler (`$CXX`, default `c++`) on the host.
//!
//! The shim is generated from the manifest:
//!
//! ```c
//! void*   vh_new(void);              // construct + first eval (runs $readmemh)
//! void    vh_free(void*);
//! void    vh_set(void*, uint32_t pin, uint8_t level);  // input balls
//! uint8_t vh_get(void*, uint32_t pin);                  // any ball
//! void    vh_cycle(void*);           // clock rise + eval, fall + eval
//! uint32_t vh_abi(void);             // ABI version (1)
//! ```
//!
//! `pin` indexes `manifest.pins`. Tied-low ports are held at 0 and the
//! clock is owned by the shim.

use std::ffi::c_void;
use std::path::{Path, PathBuf};
use std::process::Command;

use super::ChipBackend;
use crate::gateware::{sha256_hex, Artifact, GatewareDir, GatewareManifest};

const ABI: u32 = 1;

/// Verilator flags, mirroring LiteX's sim Makefile so the model is the one
/// LiteX would build.
const VERILATOR_FLAGS: &[&str] = &[
    "-Wno-fatal",
    "-O3",
    "--unroll-count",
    "256",
    "--output-split",
    "5000",
    "--output-split-cfuncs",
    "500",
    "-Wno-BLKANDNBLK",
    "-Wno-WIDTH",
    "-Wno-COMBDLY",
    "-Wno-CASEINCOMPLETE",
    "-Wno-TIMESCALEMOD",
];

/// Errors building or loading the model.
#[derive(Debug, thiserror::Error)]
pub enum HdlError {
    /// A build step failed.
    #[error("{0}")]
    Build(String),
    /// Loading the shared library failed.
    #[error("load {0}: {1}")]
    Load(String, String),
}

/// Model build settings.
#[derive(Debug, Clone)]
pub struct BuildOptions {
    /// `verilator` executable.
    pub verilator: PathBuf,
    /// C++ compiler for the shim + link step.
    pub cxx: String,
    /// Parallel compile jobs.
    pub jobs: usize,
    /// Progress messages to stderr.
    pub verbose: bool,
}

impl Default for BuildOptions {
    fn default() -> Self {
        Self {
            verilator: std::env::var_os("VERILATOR")
                .map(PathBuf::from)
                .unwrap_or_else(|| "verilator".into()),
            cxx: std::env::var("CXX").unwrap_or_else(|_| "c++".into()),
            jobs: std::thread::available_parallelism()
                .map(|n| n.get().min(8))
                .unwrap_or(4),
            verbose: true,
        }
    }
}

fn is_ident(s: &str) -> bool {
    !s.is_empty()
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !s.starts_with(|c: char| c.is_ascii_digit())
}

/// The C++ shim for a manifest.
pub fn shim_source(m: &GatewareManifest) -> Result<String, HdlError> {
    let names = std::iter::once(&m.top)
        .chain(std::iter::once(&m.clock.port))
        .chain(m.tie_low.iter())
        .chain(m.pins.iter().map(|p| &p.port));
    for n in names {
        if !is_ident(n) {
            return Err(HdlError::Build(format!("not a Verilog identifier: {n:?}")));
        }
    }
    let top = format!("V{}", m.top);
    let mut s = String::new();
    s += "// Generated by vcad-ecad-sim board_sim::verilated. Do not edit.\n";
    s += &format!("#include \"{top}.h\"\n#include \"verilated.h\"\n#include <cstdint>\n");
    s += &format!("struct VH {{ VerilatedContext* ctx; {top}* top; }};\n");
    s += "extern \"C\" {\n";
    s += &format!("uint32_t vh_abi() {{ return {ABI}; }}\n");
    s += "void* vh_new() {\n  VH* h = new VH;\n  h->ctx = new VerilatedContext;\n";
    s += &format!("  h->top = new {top}{{h->ctx}};\n");
    for t in &m.tie_low {
        s += &format!("  h->top->{t} = 0;\n");
    }
    s += &format!("  h->top->{} = 0;\n", m.clock.port);
    s += "  h->top->eval();\n  return h;\n}\n";
    s += "void vh_free(void* p) {\n  VH* h = (VH*)p;\n  h->top->final();\n  delete h->top;\n  delete h->ctx;\n  delete h;\n}\n";
    s += "void vh_set(void* p, uint32_t i, uint8_t v) {\n  auto* t = ((VH*)p)->top;\n  switch (i) {\n";
    for (i, pin) in m.pins.iter().enumerate() {
        if pin.dir == GatewareDir::In {
            s += &format!("    case {i}: t->{} = v ? 1 : 0; break;\n", pin.port);
        }
    }
    s += "    default: break;\n  }\n}\n";
    s += "uint8_t vh_get(void* p, uint32_t i) {\n  auto* t = ((VH*)p)->top;\n  switch (i) {\n";
    for (i, pin) in m.pins.iter().enumerate() {
        s += &format!("    case {i}: return t->{} & 1;\n", pin.port);
    }
    s += "    default: return 0;\n  }\n}\n";
    let c = &m.clock.port;
    s += &format!(
        "void vh_cycle(void* p) {{\n  auto* t = ((VH*)p)->top;\n  t->{c} = 1;\n  t->eval();\n  t->{c} = 0;\n  t->eval();\n}}\n"
    );
    s += "}\n";
    Ok(s)
}

fn run(cmd: &mut Command, what: &str, log: &Path) -> Result<(), HdlError> {
    let out = cmd
        .output()
        .map_err(|e| HdlError::Build(format!("{what}: {e}")))?;
    let mut text = out.stdout;
    text.extend_from_slice(&out.stderr);
    let _ = std::fs::write(log, &text);
    if !out.status.success() {
        let tail = String::from_utf8_lossy(&text);
        let tail: String = tail
            .lines()
            .rev()
            .take(20)
            .collect::<Vec<_>>()
            .into_iter()
            .rev()
            .collect::<Vec<_>>()
            .join("\n");
        return Err(HdlError::Build(format!(
            "{what} failed (log: {}):\n{tail}",
            log.display()
        )));
    }
    Ok(())
}

fn capture(cmd: &mut Command, what: &str) -> Result<String, HdlError> {
    let out = cmd
        .output()
        .map_err(|e| HdlError::Build(format!("{what}: {e}")))?;
    if !out.status.success() {
        return Err(HdlError::Build(format!("{what} failed")));
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

/// Build (or reuse) the shared library for an artifact; returns its path.
pub fn build_model(art: &Artifact, opts: &BuildOptions) -> Result<PathBuf, HdlError> {
    let shim = shim_source(&art.manifest)?;
    let version = capture(
        Command::new(&opts.verilator).arg("--version"),
        "verilator --version",
    )?;
    let key_src = format!(
        "{shim}\n{version}\n{}\n{}",
        VERILATOR_FLAGS.join(" "),
        opts.cxx
    );
    let key = &sha256_hex(key_src.as_bytes())[..16];
    // `<store>/<sha>/gateware` → `<store>/<sha>/model-<key>`.
    let base = art.root.parent().unwrap_or(&art.root);
    let dir = base.join(format!("model-{key}"));
    let lib = dir.join(if cfg!(target_os = "macos") {
        "libvcad_hdl.dylib"
    } else {
        "libvcad_hdl.so"
    });
    if lib.exists() {
        return Ok(lib);
    }
    let tmp = base.join(format!("model-{key}.tmp{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&tmp);
    std::fs::create_dir_all(&tmp).map_err(|e| HdlError::Build(format!("mkdir: {e}")))?;
    let obj = tmp.join("obj");
    if opts.verbose {
        eprintln!("[board-sim] verilating {} ({version})", art.manifest.name);
    }
    let t0 = std::time::Instant::now();
    let mut v = Command::new(&opts.verilator);
    v.current_dir(art.workdir())
        .args(["--cc", "--build", "-j", &opts.jobs.to_string()])
        .args(["--top-module", &art.manifest.top])
        .arg("--Mdir")
        .arg(&obj)
        .args(["-CFLAGS", "-fPIC"])
        .args(["-MAKEFLAGS", "OPT_FAST=-O2 OPT_SLOW=-O1 OPT_GLOBAL=-O2"])
        .args(VERILATOR_FLAGS)
        .args(art.rtl_paths());
    run(&mut v, "verilator", &tmp.join("verilator.log"))?;

    let root = capture(
        Command::new(&opts.verilator).args(["--getenv", "VERILATOR_ROOT"]),
        "verilator --getenv VERILATOR_ROOT",
    )?;
    let shim_path = tmp.join("vcad_hdl_shim.cpp");
    std::fs::write(&shim_path, &shim).map_err(|e| HdlError::Build(format!("shim: {e}")))?;
    let top_lib = obj.join(format!("lib{}.a", top_class(&art.manifest)));
    let all_lib = obj.join(format!("{}__ALL.a", top_class(&art.manifest)));
    let mut cxx = Command::new(&opts.cxx);
    cxx.args(["-shared", "-fPIC", "-O2", "-std=c++17"])
        .arg(format!("-I{root}/include"))
        .arg(format!("-I{root}/include/vltstd"))
        .arg(format!("-I{}", obj.display()))
        .arg(&shim_path)
        .arg("-o")
        .arg(tmp.join(lib.file_name().unwrap_or_default()));
    // Link the model archive and the Verilator runtime, whichever names
    // this Verilator produced.
    for a in [top_lib, all_lib, obj.join("libverilated.a")] {
        if a.exists() {
            cxx.arg(a);
        }
    }
    cxx.arg("-lpthread");
    run(&mut cxx, "shim link", &tmp.join("link.log"))?;
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::rename(&tmp, &dir).map_err(|e| HdlError::Build(format!("rename: {e}")))?;
    if opts.verbose {
        eprintln!(
            "[board-sim] model built in {:.1}s: {}",
            t0.elapsed().as_secs_f64(),
            lib.display()
        );
    }
    Ok(lib)
}

fn top_class(m: &GatewareManifest) -> String {
    format!("V{}", m.top)
}

type NewFn = unsafe extern "C" fn() -> *mut c_void;
type FreeFn = unsafe extern "C" fn(*mut c_void);
type SetFn = unsafe extern "C" fn(*mut c_void, u32, u8);
type GetFn = unsafe extern "C" fn(*mut c_void, u32) -> u8;
type CycleFn = unsafe extern "C" fn(*mut c_void);
type AbiFn = unsafe extern "C" fn() -> u32;

/// A loaded Verilated model of the artifact's gateware.
pub struct VerilatedFpga {
    handle: *mut c_void,
    free: FreeFn,
    set: SetFn,
    get: GetFn,
    cycle_fn: CycleFn,
    n_pins: usize,
    // Keeps the code the fn pointers point into mapped; dropped last.
    _lib: libloading::Library,
}

impl std::fmt::Debug for VerilatedFpga {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("VerilatedFpga")
            .field("pins", &self.n_pins)
            .finish()
    }
}

impl VerilatedFpga {
    /// Build (if needed) and load the artifact's model, then construct it.
    ///
    /// Construction runs the Verilog's initial blocks (`$readmemh`), whose
    /// paths are relative to the artifact's workdir: the process cwd is set
    /// there for the duration of the call and restored after.
    pub fn new(art: &Artifact, opts: &BuildOptions) -> Result<Self, HdlError> {
        let lib_path = build_model(art, opts)?;
        // SAFETY: loading a library this module just built from the
        // generated shim; its exported symbols have the signatures above.
        let lib = unsafe { libloading::Library::new(&lib_path) }
            .map_err(|e| HdlError::Load(lib_path.display().to_string(), e.to_string()))?;
        let sym = |name: &[u8]| -> Result<*const c_void, HdlError> {
            // SAFETY: symbol is looked up by name and only cast to the
            // matching signature below.
            unsafe { lib.get::<*const c_void>(name) }
                .map(|s| *s)
                .map_err(|e| HdlError::Load(lib_path.display().to_string(), e.to_string()))
        };
        // SAFETY: each pointer is the generated shim's function of that
        // name; the transmutes restore their declared C signatures.
        let (new, free, set, get, cycle_fn, abi) = unsafe {
            (
                std::mem::transmute::<*const c_void, NewFn>(sym(b"vh_new\0")?),
                std::mem::transmute::<*const c_void, FreeFn>(sym(b"vh_free\0")?),
                std::mem::transmute::<*const c_void, SetFn>(sym(b"vh_set\0")?),
                std::mem::transmute::<*const c_void, GetFn>(sym(b"vh_get\0")?),
                std::mem::transmute::<*const c_void, CycleFn>(sym(b"vh_cycle\0")?),
                std::mem::transmute::<*const c_void, AbiFn>(sym(b"vh_abi\0")?),
            )
        };
        // SAFETY: argument-free C function from the shim.
        let got = unsafe { abi() };
        if got != ABI {
            return Err(HdlError::Load(
                lib_path.display().to_string(),
                format!("shim ABI {got}, expected {ABI}"),
            ));
        }
        let cwd = std::env::current_dir().ok();
        std::env::set_current_dir(art.workdir())
            .map_err(|e| HdlError::Load(art.workdir().display().to_string(), e.to_string()))?;
        // SAFETY: constructs the model; returns an owned handle freed in Drop.
        let handle = unsafe { new() };
        if let Some(c) = cwd {
            let _ = std::env::set_current_dir(c);
        }
        Ok(Self {
            handle,
            free,
            set,
            get,
            cycle_fn,
            n_pins: art.manifest.pins.len(),
            _lib: lib,
        })
    }
}

impl ChipBackend for VerilatedFpga {
    fn set_input(&mut self, pin: usize, level: bool) {
        debug_assert!(pin < self.n_pins);
        // SAFETY: live handle; out-of-range or output pins are ignored by
        // the shim's switch.
        unsafe { (self.set)(self.handle, pin as u32, u8::from(level)) }
    }

    fn output(&self, pin: usize) -> bool {
        // SAFETY: live handle; the shim returns 0 for unknown pins.
        unsafe { (self.get)(self.handle, pin as u32) != 0 }
    }

    fn cycle(&mut self) {
        // SAFETY: live handle.
        unsafe { (self.cycle_fn)(self.handle) }
    }
}

impl Drop for VerilatedFpga {
    fn drop(&mut self) {
        // SAFETY: handle came from vh_new and is freed exactly once.
        unsafe { (self.free)(self.handle) }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shim_sets_only_inputs_and_rejects_bad_names() {
        let mut m: GatewareManifest = serde_json::from_value(serde_json::json!({
            "schema": "vcad.gateware/1", "name": "t", "top": "sim",
            "clock": {"port": "sys_clk", "hz": 100},
            "tie_low": ["sim_trace"],
            "rtl": [], "workdir": "rtl", "fpga_ref_part": "x",
            "pins": [
                {"ball": "L4", "signal": "serial.tx", "port": "serial_tx", "dir": "out"},
                {"ball": "M1", "signal": "serial.rx", "port": "serial_rx", "dir": "in"}
            ],
            "cpu": {"file": "x", "sha256": "y"}, "files": {}
        }))
        .unwrap();
        let s = shim_source(&m).unwrap();
        assert!(s.contains("case 1: t->serial_rx = v ? 1 : 0;"));
        assert!(!s.contains("t->serial_tx = v"));
        assert!(s.contains("case 0: return t->serial_tx & 1;"));
        assert!(s.contains("h->top->sim_trace = 0;"));
        m.pins[0].port = "a; system(\"x\")".into();
        assert!(shim_source(&m).is_err());
    }
}
