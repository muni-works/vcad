#!/usr/bin/env python3
"""Generate logo.loon: the vcad mark (docs/brand-spec.md §1) as a part.

  python3 gen-logo.py > logo.loon

A soft-filleted inverted-triangle prism (apex 63.5°) in brand orange, with
the "level sets + centroid" engraving on its front face:
  * nested level sets of the outline — inward offsets of the ▽. A uniform
    offset of a triangle is a homothety about its incentre, so each ring is
    the outline scaled about the incentre, with the fillet's corner radius
    scaled along with it (the corners follow the fillet);
  * a centroid datum (ring + crosshair) at the area centroid, which for this
    triangle sits 1.15 mm below the incentre — the level sets' centre and
    the mass centre, deliberately both present.
All engraving is real geometry: shallow groove cutters subtracted from the
face, so the path tracer catches light in them.
"""
import math

H = 100.0                      # height, mm
HW = H * math.tan(math.radians(63.5 / 2))  # half-width (0.6188 h)
DEPTH = 34.0                   # prism depth (+Y)
FILLET = 7.0                   # soft edge (variant v3)
GROOVE_DEPTH = 0.32            # mm into the face
GROOVE_W = 0.55                # groove width, mm
OFFSETS = [14.0, 19.0, 24.0]  # level-set distances from the outline, mm

A = (-HW, H)
B = (HW, H)
C = (0.0, 0.0)
side_ab = 2 * HW
side_bc = math.hypot(HW, H)
perim = side_ab + 2 * side_bc
area = HW * H
R_IN = 2 * area / perim              # inradius
INCENTRE = (0.0, H - R_IN)
CENTROID = (0.0, 2 * H / 3)


def rounded_triangle(scale, corner_r, n=10):
    """Outline scaled about the incentre, corners rounded by corner_r."""
    ix, iz = INCENTRE
    pts = [(ix + (x - ix) * scale, iz + (z - iz) * scale) for x, z in (A, B, C)]
    out = []
    for i in range(3):
        p0, p1, p2 = pts[i - 1], pts[i], pts[(i + 1) % 3]
        u = _unit(p1, p0)
        v = _unit(p1, p2)
        ang = math.acos(max(-1, min(1, u[0] * v[0] + u[1] * v[1])))
        t = corner_r / math.tan(ang / 2)          # tangent length
        bis = _unit((0, 0), (u[0] + v[0], u[1] + v[1]))
        d = corner_r / math.sin(ang / 2)
        cx, cz = p1[0] + bis[0] * d, p1[1] + bis[1] * d
        a0 = (p1[0] + u[0] * t, p1[1] + u[1] * t)
        a1 = (p1[0] + v[0] * t, p1[1] + v[1] * t)
        s = math.atan2(a0[1] - cz, a0[0] - cx)
        e = math.atan2(a1[1] - cz, a1[0] - cx)
        sweep = (e - s + math.pi) % (2 * math.pi) - math.pi
        for k in range(n + 1):
            th = s + sweep * k / n
            out.append((cx + corner_r * math.cos(th), cz + corner_r * math.sin(th)))
    return out


def _unit(a, b):
    dx, dz = b[0] - a[0], b[1] - a[1]
    m = math.hypot(dx, dz)
    return (dx / m, dz / m)


def flat(pts):
    return " ".join(f"{x:.4f} {z:.4f}" for x, z in pts)


def circle(cx, cz, r, n=48):
    return [(cx + r * math.cos(2 * math.pi * k / n), cz + r * math.sin(2 * math.pi * k / n)) for k in range(n)]


def rect(cx, cz, w, h):
    return [(cx - w / 2, cz - h / 2), (cx + w / 2, cz - h / 2), (cx + w / 2, cz + h / 2), (cx - w / 2, cz + h / 2)]


def cutter(name, outer, hole=None):
    poly = f"#[{flat(outer)}]"
    if hole is not None:
        poly += f" #[#[{flat(hole)}]]"
    return (f"[let {name} [pipe [extrude 0 {GROOVE_DEPTH + 1.0:.3f} 0\n"
            f"  [sketch 0 -1 0  1 0 0  0 0 1 #[[polygon {poly}]]]]]]")


lines = [
    "; logo.vcad — the vcad mark as a real part (docs/brand-spec.md §1).",
    "; GENERATED by gen-logo.py — edit that, then:",
    ";   python3 gen-logo.py > logo.loon",
    ";   cargo run -p vcad-loon --example loon2vcad -- logo.loon > logo.vcad",
    "; Inverted triangle, apex 63.5°, extruded into a prism, soft fillet, with",
    "; level-set contours + a centroid datum engraved into the front (y=0) face.",
    f"; inradius {R_IN:.3f} mm, incentre z={INCENTRE[1]:.3f}, centroid z={CENTROID[1]:.3f}.",
    "",
    "; Brand orange #F25C1F (spec §4), satin enamel.",
    '[material "mark" 0.949 0.361 0.122 0.0 0.3]',
    "",
    f"[let mark [pipe [extrude 0 {DEPTH} 0",
    f"  [sketch 0 0 0  1 0 0  0 0 1 #[[polygon #[{flat([A, B, C])}]]]]] [fillet {FILLET}]]]",
    "",
]
names = []
for i, d in enumerate(OFFSETS):
    s_out = (R_IN - (d - GROOVE_W / 2)) / R_IN
    s_in = (R_IN - (d + GROOVE_W / 2)) / R_IN
    # The fillet rounds the outline's corners with radius FILLET; the level
    # set at distance d keeps the same shape scaled about the incentre.
    outer = rounded_triangle(s_out, FILLET * s_out)
    inner = rounded_triangle(s_in, FILLET * s_in)
    names.append(f"ls{i}")
    lines.append(f"; level set at {d} mm")
    lines.append(cutter(f"ls{i}", outer, inner))
cx, cz = CENTROID
lines.append("; centroid datum: ring + crosshair")
lines.append(cutter("dring", circle(cx, cz, 3.0 + GROOVE_W / 2), circle(cx, cz, 3.0 - GROOVE_W / 2)))
lines.append(cutter("dh", rect(cx, cz, 11.0, GROOVE_W)))
lines.append(cutter("dv", rect(cx, cz, GROOVE_W, 11.0)))
names += ["dring", "dh", "dv"]

# Cut each groove in turn (a chain of Differences), rather than one cut by
# the union of disjoint cutters, which the boolean handled worse.
acc = "mark"
for n in names:
    acc = f"[pipe {acc} [difference {n}]]"
lines += ["", f"[let logo {acc}]", '[root logo "mark"]', ""]
print("\n".join(lines))
